use crate::rows::{quote_identifier, quote_literal};
use crate::{DatabaseError, DatabaseSession, Engine, Relation};

/// One column as the Structure view shows it.
#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Record)]
pub struct ColumnDetail {
    pub name: String,
    pub column_type: String,
    pub nullable: bool,
    /// The DEFAULT expression, or how an identity or generated column gets
    /// its value; None when there is none.
    pub default_value: Option<String>,
    pub comment: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Record)]
pub struct IndexDetail {
    pub name: String,
    /// As `pg_get_indexdef` prints it, for example
    /// "CREATE UNIQUE INDEX users_email_key ON public.users USING btree (email)".
    pub definition: String,
    pub is_unique: bool,
    pub is_primary: bool,
}

#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash, uniffi::Enum)]
pub enum ConstraintKind {
    PrimaryKey,
    ForeignKey,
    Unique,
    Check,
    Exclusion,
}

#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Record)]
pub struct ConstraintDetail {
    pub name: String,
    pub kind: ConstraintKind,
    /// As `pg_get_constraintdef` prints it, for example
    /// "FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE".
    pub definition: String,
}

/// Everything the Structure view of one table shows.
#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Record)]
pub struct TableStructure {
    pub columns: Vec<ColumnDetail>,
    pub indexes: Vec<IndexDetail>,
    pub constraints: Vec<ConstraintDetail>,
}

#[uniffi::export]
impl DatabaseSession {
    pub async fn structure(&self, relation: Relation) -> Result<TableStructure, DatabaseError> {
        match self.engine() {
            Engine::Sqlite | Engine::Libsql => return self.sqlite_structure(&relation).await,
            Engine::Mysql => return self.mysql_structure(&relation).await,
            Engine::Postgres => {}
        }
        let regclass = relation.regclass()?;
        let column_rows = self
            .text_rows(format!(
                "SELECT a.attname, format_type(a.atttypid, a.atttypmod), NOT a.attnotnull,
                        CASE
                          WHEN a.attidentity = 'a' THEN 'GENERATED ALWAYS AS IDENTITY'
                          WHEN a.attidentity = 'd' THEN 'GENERATED BY DEFAULT AS IDENTITY'
                          WHEN a.attgenerated = 's' THEN 'GENERATED ALWAYS AS (' || pg_get_expr(d.adbin, d.adrelid) || ') STORED'
                          ELSE pg_get_expr(d.adbin, d.adrelid)
                        END,
                        col_description(a.attrelid, a.attnum)
                 FROM pg_attribute a
                 LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
                 WHERE a.attrelid = {regclass} AND a.attnum > 0 AND NOT a.attisdropped
                 ORDER BY a.attnum"
            ))
            .await?;
        let index_rows = self
            .text_rows(format!(
                "SELECT c.relname, pg_get_indexdef(i.indexrelid), i.indisunique, i.indisprimary
                 FROM pg_index i JOIN pg_class c ON c.oid = i.indexrelid
                 WHERE i.indrelid = {regclass}
                 ORDER BY i.indisprimary DESC, c.relname"
            ))
            .await?;
        let constraint_rows = self
            .text_rows(format!(
                "SELECT conname, contype, pg_get_constraintdef(oid)
                 FROM pg_constraint
                 WHERE conrelid = {regclass} AND contype IN ('p', 'f', 'u', 'c', 'x')
                 ORDER BY CASE contype WHEN 'p' THEN 1 WHEN 'f' THEN 2 WHEN 'u' THEN 3 WHEN 'c' THEN 4 ELSE 5 END, conname"
            ))
            .await?;

        let columns = column_rows
            .into_iter()
            .filter_map(|row| {
                let [Some(name), Some(column_type), Some(nullable), default_value, comment] =
                    <[Option<String>; 5]>::try_from(row).ok()?
                else {
                    return None;
                };
                Some(ColumnDetail { name, column_type, nullable: nullable == "t", default_value, comment })
            })
            .collect();
        let indexes = index_rows
            .into_iter()
            .filter_map(|row| {
                let [Some(name), Some(definition), Some(unique), Some(primary)] =
                    <[Option<String>; 4]>::try_from(row).ok()?
                else {
                    return None;
                };
                Some(IndexDetail { name, definition, is_unique: unique == "t", is_primary: primary == "t" })
            })
            .collect();
        let constraints = constraint_rows
            .into_iter()
            .filter_map(|row| {
                let [Some(name), Some(kind), Some(definition)] = <[Option<String>; 3]>::try_from(row).ok()? else {
                    return None;
                };
                let kind = match kind.as_str() {
                    "p" => ConstraintKind::PrimaryKey,
                    "f" => ConstraintKind::ForeignKey,
                    "u" => ConstraintKind::Unique,
                    "c" => ConstraintKind::Check,
                    "x" => ConstraintKind::Exclusion,
                    _ => return None,
                };
                Some(ConstraintDetail { name, kind, definition })
            })
            .collect();
        Ok(TableStructure { columns, indexes, constraints })
    }
}

/// A column as the user describes it in the Structure view. `column_type`
/// and `default_value` are SQL as typed (`varchar(255)`, `now()`).
#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Record)]
pub struct ColumnSpec {
    pub name: String,
    pub column_type: String,
    pub nullable: bool,
    pub default_value: Option<String>,
    pub comment: Option<String>,
}

/// One change to a table's structure, made from the Structure view.
#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Enum)]
pub enum StructureChange {
    AddColumn { column: ColumnSpec },
    /// Only what differs between `original` and `column` is changed.
    EditColumn { original: ColumnDetail, column: ColumnSpec },
    DropColumn { name: String, cascade: bool },
    AddIndex { name: String, columns: Vec<String>, unique: bool },
    DropIndex { name: String, cascade: bool },
    AddForeignKey {
        name: Option<String>,
        column: String,
        referenced: Relation,
        referenced_column: String,
        /// `CASCADE`, `SET NULL`, `RESTRICT`… ; None for the default, NO ACTION.
        on_delete: Option<String>,
    },
    DropConstraint { name: String, cascade: bool },
}

/// Identity, generated and MySQL AUTO_INCREMENT columns show how they get
/// their value where a default would be; that text isn't a DEFAULT expression.
pub(crate) fn is_generated(default_value: &Option<String>) -> bool {
    default_value.as_deref().is_some_and(|text| text.starts_with("GENERATED ") || text == "AUTO_INCREMENT")
}

pub(crate) fn non_empty(text: &Option<String>) -> Option<&str> {
    text.as_deref().map(str::trim).filter(|text| !text.is_empty())
}

pub(crate) const REFERENTIAL_ACTIONS: &[&str] = &["NO ACTION", "RESTRICT", "CASCADE", "SET NULL", "SET DEFAULT"];

/// The statements that make `change` on `relation`, in order. They are run
/// together, in one transaction, by [`DatabaseSession::apply_structure_change`].
#[uniffi::export]
pub fn structure_change_sql(relation: Relation, change: StructureChange, engine: Engine) -> Result<Vec<String>, DatabaseError> {
    match engine {
        Engine::Sqlite | Engine::Libsql => return sqlite_structure_change_sql(&relation, change),
        Engine::Mysql => return crate::mysql::structure_change_sql(&relation, &change, None),
        Engine::Postgres => {}
    }
    let table = format!("ALTER TABLE {}", relation.quoted_name());
    let schema = quote_identifier(&relation.schema);
    let column_name = |name: &str| -> Result<String, DatabaseError> {
        if name.trim().is_empty() {
            return Err(DatabaseError::new("The column needs a name."));
        }
        Ok(quote_identifier(name.trim()))
    };
    let comment_sql = |column: &str, comment: &Option<String>| -> Result<String, DatabaseError> {
        let value = match non_empty(comment) {
            Some(text) => quote_literal(text)?,
            None => "NULL".to_string(),
        };
        Ok(format!("COMMENT ON COLUMN {}.{column} IS {value};", relation.quoted_name()))
    };

    let mut statements = Vec::new();
    match change {
        StructureChange::AddColumn { column } => {
            let name = column_name(&column.name)?;
            let column_type = column.column_type.trim();
            if column_type.is_empty() {
                return Err(DatabaseError::new("The column needs a type."));
            }
            let mut sql = format!("{table} ADD COLUMN {name} {column_type}");
            if !column.nullable {
                sql += " NOT NULL";
            }
            if let Some(default) = non_empty(&column.default_value) {
                sql += &format!(" DEFAULT {default}");
            }
            statements.push(sql + ";");
            if non_empty(&column.comment).is_some() {
                statements.push(comment_sql(&name, &column.comment)?);
            }
        }
        StructureChange::EditColumn { original, column } => {
            let old = quote_identifier(&original.name);
            let name = column_name(&column.name)?;
            if column.name.trim() != original.name {
                statements.push(format!("{table} RENAME COLUMN {old} TO {name};"));
            }
            let column_type = column.column_type.trim();
            if column_type.is_empty() {
                return Err(DatabaseError::new("The column needs a type."));
            }
            if column_type != original.column_type {
                // USING converts the stored values; without it Postgres refuses
                // most type changes (text to integer, for example).
                statements.push(format!("{table} ALTER COLUMN {name} TYPE {column_type} USING {name}::{column_type};"));
            }
            if column.nullable != original.nullable {
                let action = if column.nullable { "DROP" } else { "SET" };
                statements.push(format!("{table} ALTER COLUMN {name} {action} NOT NULL;"));
            }
            let new_default = non_empty(&column.default_value);
            if !is_generated(&original.default_value) && new_default != non_empty(&original.default_value) {
                statements.push(match new_default {
                    Some(default) => format!("{table} ALTER COLUMN {name} SET DEFAULT {default};"),
                    None => format!("{table} ALTER COLUMN {name} DROP DEFAULT;"),
                });
            }
            if non_empty(&column.comment) != non_empty(&original.comment) {
                statements.push(comment_sql(&name, &column.comment)?);
            }
        }
        StructureChange::DropColumn { name, cascade } => {
            statements.push(format!("{table} DROP COLUMN {}{};", column_name(&name)?, if cascade { " CASCADE" } else { "" }));
        }
        StructureChange::AddIndex { name, columns, unique } => {
            if columns.is_empty() {
                return Err(DatabaseError::new("Choose at least one column for the index."));
            }
            if name.trim().is_empty() {
                return Err(DatabaseError::new("The index needs a name."));
            }
            let columns = columns.iter().map(|column| quote_identifier(column)).collect::<Vec<_>>().join(", ");
            statements.push(format!(
                "CREATE {}INDEX {} ON {} ({columns});",
                if unique { "UNIQUE " } else { "" },
                quote_identifier(name.trim()),
                relation.quoted_name()
            ));
        }
        StructureChange::DropIndex { name, cascade } => {
            // An index lives in its table's schema.
            statements.push(format!("DROP INDEX {schema}.{}{};", quote_identifier(&name), if cascade { " CASCADE" } else { "" }));
        }
        StructureChange::AddForeignKey { name, column, referenced, referenced_column, on_delete } => {
            let mut sql = table.clone();
            if let Some(name) = non_empty(&name) {
                sql += &format!(" ADD CONSTRAINT {}", quote_identifier(name));
            } else {
                sql += " ADD";
            }
            sql += &format!(
                " FOREIGN KEY ({}) REFERENCES {} ({})",
                column_name(&column)?,
                referenced.quoted_name(),
                column_name(&referenced_column)?
            );
            if let Some(action) = non_empty(&on_delete) {
                let action = action.to_uppercase();
                if !REFERENTIAL_ACTIONS.contains(&action.as_str()) {
                    return Err(DatabaseError::new(format!("Unknown ON DELETE action: {action}.")));
                }
                sql += &format!(" ON DELETE {action}");
            }
            statements.push(sql + ";");
        }
        StructureChange::DropConstraint { name, cascade } => {
            statements.push(format!("{table} DROP CONSTRAINT {}{};", quote_identifier(&name), if cascade { " CASCADE" } else { "" }));
        }
    }
    Ok(statements)
}

#[uniffi::export]
impl DatabaseSession {
    /// Runs a change's statements as one transaction: all of them or none.
    /// Sent as one message, they form one implicit transaction that Postgres
    /// rolls back on its own when a statement fails; an explicit BEGIN would
    /// leave the session in a failed transaction instead.
    pub async fn apply_structure_change(&self, relation: Relation, change: StructureChange) -> Result<(), DatabaseError> {
        if let Some(link) = self.mysql() {
            // MySQL commits each DDL statement on its own; most changes are one statement.
            let statements = self.structure_change_statements(relation, change).await?;
            return crate::on_runtime(async move {
                for statement in statements {
                    link.execute(statement).await?;
                }
                Ok(())
            })
            .await;
        }
        if let Some(link) = self.sqlite().filter(|_| crate::sqlite_rebuild::needs_rebuild(&change)) {
            let rebuild = self.sqlite_rebuild(&relation, change).await?;
            let schema = relation.schema.clone();
            return crate::on_runtime(async move { link.rebuild(rebuild, schema).await }).await;
        }
        let statements = structure_change_sql(relation, change, self.engine())?;
        if statements.is_empty() {
            return Ok(());
        }
        if let Some(link) = self.sqlite() {
            return crate::on_runtime(async move { link.apply_checked(statements, 0).await }).await;
        }
        self.execute(statements.join("\n")).await
    }
}

#[uniffi::export]
impl DatabaseSession {
    /// The statements [`Self::apply_structure_change`] runs, for showing
    /// before Apply. On SQLite, some changes rebuild the table, which needs
    /// its current definition.
    pub async fn structure_change_statements(&self, relation: Relation, change: StructureChange) -> Result<Vec<String>, DatabaseError> {
        if self.engine().is_sqlite() && crate::sqlite_rebuild::needs_rebuild(&change) {
            return Ok(self.sqlite_rebuild(&relation, change).await?.statements);
        }
        if self.engine() == Engine::Mysql {
            return self.mysql_structure_change_sql(&relation, change).await;
        }
        structure_change_sql(relation, change, self.engine())
    }
}

/// One column of a table being created.
#[derive(Debug, Clone, PartialEq, Eq, Hash, uniffi::Record)]
pub struct NewTableColumn {
    pub column: ColumnSpec,
    /// Part of the primary key; several columns make a composite key.
    pub primary_key: bool,
}

/// `CREATE TABLE`, then a `COMMENT ON COLUMN` for each comment. Run together
/// by [`DatabaseSession::create_table`], in one transaction.
#[uniffi::export]
pub fn create_table_sql(schema: String, name: String, columns: Vec<NewTableColumn>, engine: Engine) -> Result<Vec<String>, DatabaseError> {
    if engine.is_sqlite() && columns.iter().any(|entry| non_empty(&entry.column.comment).is_some()) {
        return Err(DatabaseError::new("SQLite has no column comments."));
    }
    let name = name.trim();
    if name.is_empty() {
        return Err(DatabaseError::new("The table needs a name."));
    }
    if columns.is_empty() {
        return Err(DatabaseError::new("Add at least one column."));
    }
    let table = format!("{}.{}", quote_identifier(&schema), quote_identifier(name));
    let mut seen = std::collections::HashSet::new();
    let mut definitions = Vec::new();
    let mut key = Vec::new();
    let mut comments = Vec::new();
    for (position, entry) in columns.iter().enumerate() {
        let column = &entry.column;
        let column_name = column.name.trim();
        if column_name.is_empty() {
            return Err(DatabaseError::new(format!("Column {} needs a name.", position + 1)));
        }
        if !seen.insert(column_name.to_string()) {
            return Err(DatabaseError::new(format!("Two columns are named {column_name}.")));
        }
        let column_type = column.column_type.trim();
        if column_type.is_empty() {
            return Err(DatabaseError::new(format!("Column {column_name} needs a type.")));
        }
        let quoted = quote_identifier(column_name);
        let mut definition = format!("  {quoted} {column_type}");
        // Key columns are NOT NULL anyway; saying it again would be noise.
        if !column.nullable && !entry.primary_key {
            definition += " NOT NULL";
        }
        match non_empty(&column.default_value) {
            // MySQL numbers rows with a column attribute, not a default.
            Some("AUTO_INCREMENT") if engine == Engine::Mysql => definition += " AUTO_INCREMENT",
            Some(default) => definition += &format!(" DEFAULT {default}"),
            None => {}
        }
        // MySQL keeps a column's comment in its definition.
        if let (Engine::Mysql, Some(comment)) = (engine, non_empty(&column.comment)) {
            definition += &format!(" COMMENT {}", quote_literal(comment)?);
        }
        definitions.push(definition);
        if entry.primary_key {
            key.push(quoted.clone());
        }
        if let Some(comment) = non_empty(&column.comment).filter(|_| engine != Engine::Mysql) {
            comments.push(format!("COMMENT ON COLUMN {table}.{quoted} IS {};", quote_literal(comment)?));
        }
    }
    if !key.is_empty() {
        definitions.push(format!("  PRIMARY KEY ({})", key.join(", ")));
    }
    let mut statements = vec![format!("CREATE TABLE {table} (\n{}\n);", definitions.join(",\n"))];
    statements.extend(comments);
    Ok(statements)
}

#[uniffi::export]
impl DatabaseSession {
    /// Creates the table and its column comments as one transaction.
    pub async fn create_table(&self, schema: String, name: String, columns: Vec<NewTableColumn>) -> Result<(), DatabaseError> {
        let statements = create_table_sql(schema, name, columns, self.engine())?;
        if let Some(link) = self.sqlite() {
            return crate::on_runtime(async move { link.apply_checked(statements, 0).await }).await;
        }
        self.execute(statements.join("\n")).await
    }
}

/// What SQLite can change in place. A column's type, NULL or default and
/// constraints need a table rebuild, which comes in its own step; until
/// then they are refused with the reason, and nothing changes.
fn sqlite_structure_change_sql(relation: &Relation, change: StructureChange) -> Result<Vec<String>, DatabaseError> {
    let table = format!("ALTER TABLE {}", relation.quoted_name());
    let rebuild = |what: &str| {
        DatabaseError::new(format!("SQLite can't {what} in place; TablePort rebuilds the table for it."))
    };
    let column_name = |name: &str| -> Result<String, DatabaseError> {
        if name.trim().is_empty() {
            return Err(DatabaseError::new("The column needs a name."));
        }
        Ok(quote_identifier(name.trim()))
    };
    match change {
        StructureChange::AddColumn { column } => {
            if non_empty(&column.comment).is_some() {
                return Err(DatabaseError::new("SQLite has no column comments."));
            }
            let column_type = column.column_type.trim();
            let mut sql = format!("{table} ADD COLUMN {} {column_type}", column_name(&column.name)?);
            if !column.nullable {
                sql += " NOT NULL";
            }
            if let Some(default) = non_empty(&column.default_value) {
                sql += &format!(" DEFAULT {}", crate::sqlite_rebuild::default_expression(default));
            }
            Ok(vec![sql + ";"])
        }
        StructureChange::EditColumn { original, column } => {
            if column.column_type.trim() != original.column_type {
                return Err(rebuild("change a column's type"));
            }
            if column.nullable != original.nullable {
                return Err(rebuild("change whether a column allows NULL"));
            }
            if non_empty(&column.default_value) != non_empty(&original.default_value) {
                return Err(rebuild("change a column's default"));
            }
            if non_empty(&column.comment).is_some() {
                return Err(DatabaseError::new("SQLite has no column comments."));
            }
            let name = column_name(&column.name)?;
            if column.name.trim() == original.name {
                return Ok(Vec::new());
            }
            Ok(vec![format!("{table} RENAME COLUMN {} TO {name};", quote_identifier(&original.name))])
        }
        StructureChange::DropColumn { name, .. } => Ok(vec![format!("{table} DROP COLUMN {};", column_name(&name)?)]),
        StructureChange::AddIndex { name, columns, unique } => {
            if columns.is_empty() {
                return Err(DatabaseError::new("Choose at least one column for the index."));
            }
            if name.trim().is_empty() {
                return Err(DatabaseError::new("The index needs a name."));
            }
            // SQLite names the schema on the index, and the table without it.
            let columns = columns.iter().map(|column| quote_identifier(column)).collect::<Vec<_>>().join(", ");
            Ok(vec![format!(
                "CREATE {}INDEX {}.{} ON {} ({columns});",
                if unique { "UNIQUE " } else { "" },
                quote_identifier(&relation.schema),
                quote_identifier(name.trim()),
                quote_identifier(&relation.name)
            )])
        }
        StructureChange::DropIndex { name, .. } => {
            Ok(vec![format!("DROP INDEX {}.{};", quote_identifier(&relation.schema), quote_identifier(&name))])
        }
        StructureChange::AddForeignKey { .. } => Err(rebuild("add a foreign key")),
        StructureChange::DropConstraint { .. } => Err(rebuild("drop a constraint")),
    }
}
