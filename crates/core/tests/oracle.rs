//! Oracle tests need Instant Client and a login that may create tables in
//! its own schema:
//!
//! ```text
//! TABLEPORT_ORACLE_CLIENT=~/Downloads/instantclient_23_3 \
//! TABLEPORT_TEST_ORACLE='(description=…)' or 'host:1521/service' \
//! TABLEPORT_TEST_ORACLE_USER=admin TABLEPORT_TEST_ORACLE_PASSWORD=… cargo test
//! ```
//!
//! Without them the tests pass without running. Each test makes its own
//! tables, named after it, and drops them afterwards.

use std::collections::HashMap;
use std::sync::Arc;

use tableport_core::{ConnectionSettings, DatabaseSession, Engine, Relation, RelationKind, TlsMode};

fn settings() -> Option<ConnectionSettings> {
    let client = std::env::var("TABLEPORT_ORACLE_CLIENT").ok()?;
    let target = std::env::var("TABLEPORT_TEST_ORACLE").ok()?;
    tableport_core::load_oracle_client(client).expect("Instant Client loads");
    let (host, port, database) = if target.trim_start().starts_with('(') {
        (target, 0, String::new())
    } else {
        let (address, service) = target.split_once('/')?;
        let (host, port) = address.rsplit_once(':').unwrap_or((address, "1521"));
        (host.to_string(), port.parse().ok()?, service.to_string())
    };
    Some(ConnectionSettings {
        host,
        port,
        database,
        user: std::env::var("TABLEPORT_TEST_ORACLE_USER").ok()?,
        password: std::env::var("TABLEPORT_TEST_ORACLE_PASSWORD").ok(),
        tls: if std::env::var("TABLEPORT_TEST_ORACLE_TLS").is_ok() { TlsMode::Require } else { TlsMode::Disable },
        ssh: None,
        read_only: false,
        engine: Engine::Oracle,
    })
}

/// Runs `body` with fresh TEAMS_n and USERS_n tables, dropped afterwards.
async fn with_tables<F, Fut>(name: &str, body: F)
where
    F: FnOnce(Arc<DatabaseSession>, Relation, Relation) -> Fut,
    Fut: std::future::Future<Output = ()>,
{
    let Some(settings) = settings() else { return };
    let session = DatabaseSession::connect(settings).await.expect("connect");
    let schema = session.schemas().await.unwrap().into_iter().find(|schema| schema.name == session.settings().user.to_uppercase()).map(|schema| schema.name).unwrap_or_else(|| session.settings().user.to_uppercase());
    let suffix = format!("{}_{}", name.to_uppercase(), std::process::id());
    let teams = Relation { schema: schema.clone(), name: format!("TEAMS_{suffix}"), kind: RelationKind::Table };
    let users = Relation { schema: schema.clone(), name: format!("USERS_{suffix}"), kind: RelationKind::Table };
    let drop = |relation: &Relation| format!("BEGIN EXECUTE IMMEDIATE 'DROP TABLE {} CASCADE CONSTRAINTS PURGE'; EXCEPTION WHEN OTHERS THEN NULL; END;", tableport_core::qualified_name(relation.clone(), Engine::Oracle).replace('\'', "''"));
    session.execute(drop(&users)).await.unwrap();
    session.execute(drop(&teams)).await.unwrap();
    let setup = format!(
        "CREATE TABLE {teams} (id NUMBER(10) PRIMARY KEY, name VARCHAR2(40 CHAR) NOT NULL);\n\
         CREATE TABLE {users} (id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR2(80 CHAR), score NUMBER(6,2), \
            joined DATE, seen TIMESTAMP, avatar RAW(16), notes CLOB, team_id NUMBER(10) REFERENCES {teams} (id));\n\
         INSERT INTO {teams} VALUES (1, 'Core');\n\
         INSERT INTO {teams} VALUES (2, 'Apps');\n\
         INSERT INTO {users} (name, score, joined, seen, avatar, notes, team_id) VALUES ('Ada', 9.5, DATE '2024-01-02', TIMESTAMP '2024-01-02 03:04:05.5', HEXTORAW('CAFE'), 'long note', 1);\n\
         INSERT INTO {users} (name, score, team_id) VALUES ('Grace', 7, 2);\n\
         INSERT INTO {users} (name) VALUES ('alan');\n\
         INSERT INTO {users} (name, score, team_id) VALUES ('100% sure', 0.5, 1);\n\
         INSERT INTO {users} (name) VALUES ('Zoë ✓')",
        teams = tableport_core::qualified_name(teams.clone(), Engine::Oracle),
        users = tableport_core::qualified_name(users.clone(), Engine::Oracle)
    );
    session.execute(setup).await.expect("set up the tables");
    let outcome = futures::FutureExt::catch_unwind(std::panic::AssertUnwindSafe(body(session.clone(), users.clone(), teams.clone()))).await;
    session.execute(drop(&users)).await.unwrap();
    session.execute(drop(&teams)).await.unwrap();
    if let Err(panic) = outcome {
        std::panic::resume_unwind(panic);
    }
}

#[tokio::test]
async fn connects_and_names_the_server() {
    let Some(settings) = settings() else { return };
    let session = DatabaseSession::connect(settings.clone()).await.unwrap();
    assert!(session.server_version().starts_with("Oracle "), "{}", session.server_version());
    session.ping().await.unwrap();
    let wrong = ConnectionSettings { password: Some("wrong-Password-1".into()), ..settings };
    let error = tableport_core::test_connection(wrong).await.unwrap_err();
    assert!(error.message().contains("ORA-01017"), "{error}");
}

#[tokio::test]
async fn browses_pages_and_filters() {
    use tableport_core::{FilterOperator, FilterTarget, RowFilter, RowSort};
    with_tables("browse", |session, users, teams| async move {
        let schemas = session.schemas().await.unwrap();
        let ours = schemas.iter().find(|schema| schema.name == users.schema).unwrap();
        assert!(ours.relations.iter().any(|relation| relation.name == users.name));
        assert!(schemas.iter().all(|schema| schema.name != "SYS"));

        let columns = session.columns(users.clone()).await.unwrap();
        let summary: Vec<_> = columns.iter().map(|column| (column.name.as_str(), column.column_type.as_str(), column.is_numeric)).collect();
        assert_eq!(summary[..3], [("ID", "NUMBER", true), ("NAME", "VARCHAR2(80 CHAR)", false), ("SCORE", "NUMBER(6,2)", true)]);
        assert_eq!(session.primary_key(users.clone()).await.unwrap(), ["ID"]);
        let keys = session.foreign_keys(users.clone()).await.unwrap();
        assert_eq!((keys[0].column.as_str(), keys[0].referenced_relation.name.as_str()), ("TEAM_ID", teams.name.as_str()));

        let key = vec!["ID".to_string()];
        let page = session.rows(users.clone(), columns.clone(), Vec::new(), None, key.clone(), 0, 2).await.unwrap();
        assert_eq!(page.rows.len(), 2);
        assert_eq!(page.rows[0][1].as_deref(), Some("Ada"));
        assert_eq!(page.rows[0][2].as_deref(), Some("9.5"));
        assert_eq!(page.rows[0][3].as_deref(), Some("2024-01-02 00:00:00"));
        assert_eq!(page.rows[0][4].as_deref(), Some("2024-01-02 03:04:05.5"));
        assert_eq!(page.rows[0][5].as_deref(), Some("\\xcafe"));
        assert_eq!(page.rows[0][6].as_deref(), Some("long note"));

        let filter = |target, operator, value: &str| RowFilter { target, operator, value: value.into() };
        let name = || FilterTarget::Column { name: "NAME".into() };
        let count = |filters: Vec<RowFilter>| {
            let session = session.clone();
            let relation = users.clone();
            let columns = columns.clone();
            async move { session.row_count(relation, columns, filters).await.unwrap() }
        };
        assert_eq!(count(vec![]).await, 5);
        assert_eq!(count(vec![filter(name(), FilterOperator::Contains, "a")]).await, 3, "Ada, Grace, alan: no case");
        assert_eq!(count(vec![filter(name(), FilterOperator::Contains, "%")]).await, 1);
        assert_eq!(count(vec![filter(name(), FilterOperator::Equals, "Zoë ✓")]).await, 1);
        assert_eq!(count(vec![filter(FilterTarget::Column { name: "SCORE".into() }, FilterOperator::NotEquals, "7")]).await, 4);
        assert_eq!(count(vec![filter(FilterTarget::Column { name: "JOINED".into() }, FilterOperator::GreaterOrEqual, "2024-01-01 00:00:00")]).await, 1);
        assert_eq!(count(vec![filter(FilterTarget::AnyColumn, FilterOperator::Contains, "sure")]).await, 1);
        assert_eq!(count(vec![filter(FilterTarget::RawSql, FilterOperator::Equals, "team_id = 1")]).await, 2);
        assert_eq!(count(vec![filter(name(), FilterOperator::Equals, "x' OR 1=1 --")]).await, 0);
        let sorted = session.rows(users.clone(), columns.clone(), Vec::new(), Some(RowSort { column: "NAME".into(), ascending: false }), key.clone(), 0, 1).await.unwrap();
        assert_eq!(sorted.rows[0][1].as_deref(), Some("alan"), "Oracle sorts by code point: lowercase after uppercase");
        // 0.5 is found again by its key value, which TO_CHAR would write as .5.
        let full = session.full_rows(users.clone(), columns.clone(), vec!["SCORE".into()], vec![vec!["0.5".into()]]).await.unwrap();
        assert_eq!(full.len(), 1);
    })
    .await;
}

#[tokio::test]
async fn commits_runs_scripts_and_cancels() {
    use tableport_core::{CellDraft, NewRow, PendingChanges, RowUpdate, SqlFunction};
    with_tables("commit", |session, users, _teams| async move {
        let columns = session.columns(users.clone()).await.unwrap();
        let key = vec!["ID".to_string()];
        let value = |text: &str| CellDraft::Value { text: text.into() };
        let names = |session: Arc<DatabaseSession>, users: Relation| async move {
            let result = session.run_query(format!("SELECT name FROM {} ORDER BY id", tableport_core::qualified_name(users.clone(), Engine::Oracle)), 100).await.unwrap();
            result.result_sets[0].rows.iter().map(|row| row[0].clone()).collect::<Vec<_>>()
        };
        let changes = PendingChanges {
            inserts: vec![NewRow { values: HashMap::from([("NAME".into(), value("it's ✓")), ("JOINED".into(), CellDraft::Function { function: SqlFunction::Now })]) }, NewRow::default()],
            updates: vec![RowUpdate { key: vec!["2".into()], values: HashMap::from([("NAME".into(), value("Grace H.")), ("SEEN".into(), value("2024-05-06 07:08:09"))]) }],
            deletes: vec![vec!["3".into()]],
        };
        session.commit(changes, users.clone(), columns.clone(), key.clone()).await.unwrap();
        let after = names(session.clone(), users.clone()).await;
        assert_eq!(after[..2], [Some("Ada".into()), Some("Grace H.".into())]);
        assert_eq!(after.len(), 6);

        let stale = PendingChanges {
            updates: vec![
                RowUpdate { key: vec!["1".into()], values: HashMap::from([("NAME".into(), value("changed"))]) },
                RowUpdate { key: vec!["99".into()], values: HashMap::from([("NAME".into(), value("gone"))]) },
            ],
            ..Default::default()
        };
        assert!(session.commit(stale, users.clone(), columns.clone(), key.clone()).await.unwrap_err().message().contains("someone else"));
        assert_eq!(names(session.clone(), users.clone()).await, after);

        // A script with SQL and a PL/SQL block; counts per statement; rolled back on error.
        let table = tableport_core::qualified_name(users.clone(), Engine::Oracle);
        let script = format!("UPDATE {table} SET score = 1 WHERE score IS NULL;\nBEGIN\n  UPDATE {table} SET name = name WHERE id = 1;\nEND;\n/\nSELECT name FROM {table} ORDER BY id");
        let result = session.run_query(script, 2).await.unwrap();
        assert_eq!(result.statement_verbs, ["UPDATE", "BEGIN", "SELECT"]);
        assert_eq!(result.result_sets[0].rows.len(), 2);
        let error = session.run_query(format!("UPDATE {table} SET name = 'x';\nSELECT * FROM nope"), 1).await.unwrap_err();
        assert!(error.message().starts_with("ORA-00942"), "{error}");
        assert!(!names(session.clone(), users.clone()).await.contains(&Some("x".into())));

        // Cancel breaks a long query; the session keeps working.
        let running = {
            let session = session.clone();
            tokio::spawn(async move { session.run_query("SELECT COUNT(*) FROM all_objects, all_objects, all_objects".into(), 1).await })
        };
        tokio::time::sleep(std::time::Duration::from_secs(2)).await;
        session.cancel_query().await.unwrap();
        let outcome = running.await.unwrap();
        assert!(outcome.unwrap_err().message().contains("ORA-01013"));
        assert!(session.run_query("SELECT 1 FROM dual".into(), 1).await.is_ok());

        // A read-only connection refuses changes.
        let read_only = DatabaseSession::connect(ConnectionSettings { read_only: true, ..session.settings() }).await.unwrap();
        assert!(read_only.run_query(format!("DELETE FROM {table}"), 1).await.is_err());
        assert!(read_only.run_query(format!("SELECT COUNT(*) FROM {table}"), 1).await.is_ok());
    })
    .await;
}

#[tokio::test]
async fn exports_and_changes_structure() {
    use tableport_core::{ColumnSpec, ConstraintKind, ExportFormat, ExportScope, StructureChange};
    with_tables("structure", |session, users, teams| async move {
        let columns = session.columns(users.clone()).await.unwrap();
        let path = std::env::temp_dir().join(format!("tableport-oracle-{}.sql", std::process::id())).to_string_lossy().into_owned();
        let count = session.export_rows(users.clone(), columns.clone(), Vec::new(), None, vec!["ID".into()], ExportScope::All, ExportFormat::Sql, path.clone()).await.unwrap();
        assert_eq!(count, 5);
        let sql = std::fs::read_to_string(&path).unwrap();
        assert!(sql.contains("TO_TIMESTAMP('2024-01-02 03:04:05.5'") && sql.contains("HEXTORAW('cafe')"), "{sql}");
        std::fs::remove_file(&path).ok();

        let structure = session.structure(users.clone()).await.unwrap();
        let column = |name: &str| structure.columns.iter().find(|column| column.name == name).unwrap().clone();
        assert_eq!(column("ID").default_value.as_deref(), Some("GENERATED BY DEFAULT AS IDENTITY"));
        assert!(structure.constraints.iter().any(|constraint| constraint.kind == ConstraintKind::ForeignKey));
        assert!(structure.constraints.iter().all(|constraint| !constraint.definition.contains("IS NOT NULL")));

        let apply = |change: StructureChange| {
            let session = session.clone();
            let relation = users.clone();
            async move { session.apply_structure_change(relation, change).await }
        };
        let spec = |detail: &tableport_core::ColumnDetail| ColumnSpec {
            name: detail.name.clone(),
            column_type: detail.column_type.clone(),
            nullable: detail.nullable,
            default_value: detail.default_value.clone(),
            comment: detail.comment.clone(),
        };
        let name = column("NAME");
        apply(StructureChange::EditColumn {
            original: name.clone(),
            column: ColumnSpec { name: "FULL_NAME".into(), column_type: "VARCHAR2(120 CHAR)".into(), default_value: Some("'?'".into()), comment: Some("shown name".into()), ..spec(&name) },
        })
        .await
        .unwrap();
        let after = session.structure(users.clone()).await.unwrap();
        let renamed = after.columns.iter().find(|column| column.name == "FULL_NAME").unwrap();
        assert_eq!((renamed.column_type.as_str(), renamed.default_value.as_deref(), renamed.comment.as_deref()), ("VARCHAR2(120 CHAR)", Some("'?'"), Some("shown name")));
        let note = ColumnSpec { name: "NOTE".into(), column_type: "VARCHAR2(10)".into(), nullable: false, default_value: Some("'n/a'".into()), comment: None };
        apply(StructureChange::AddColumn { column: note }).await.unwrap();
        apply(StructureChange::AddIndex { name: format!("{}_BY_NOTE", users.name), columns: vec!["NOTE".into()], unique: false }).await.unwrap();
        apply(StructureChange::DropIndex { name: format!("{}_BY_NOTE", users.name), cascade: false }).await.unwrap();
        apply(StructureChange::DropColumn { name: "NOTE".into(), cascade: false }).await.unwrap();
        let foreign = after.constraints.iter().find(|constraint| constraint.kind == ConstraintKind::ForeignKey).unwrap().name.clone();
        apply(StructureChange::DropConstraint { name: foreign, cascade: false }).await.unwrap();
        apply(StructureChange::AddForeignKey { name: None, column: "TEAM_ID".into(), referenced: teams.clone(), referenced_column: "ID".into(), on_delete: Some("set null".into()) })
            .await
            .unwrap();
        // The primary key's index goes with its constraint.
        let primary = session.structure(teams.clone()).await.unwrap().indexes.into_iter().find(|index| index.is_primary).unwrap();
        let teams_change = StructureChange::DropIndex { name: primary.name, cascade: true };
        let statements = session.structure_change_statements(teams.clone(), teams_change).await.unwrap();
        assert!(statements[0].contains("DROP CONSTRAINT"), "{statements:?}");
    })
    .await;
}

#[tokio::test]
async fn ai_access_is_read_only() {
    use serde_json::{json, Value};
    use tableport_core::{McpConnection, McpHost, McpLogEntry};
    struct Host {
        settings: ConnectionSettings,
    }
    impl McpHost for Host {
        fn connections(&self) -> Vec<McpConnection> {
            vec![McpConnection { id: "o".into(), name: "Oracle".into(), database: self.settings.database.clone(), all_databases: false, tag: None, engine: Engine::Oracle }]
        }
        fn settings(&self, _connection_id: String) -> Option<ConnectionSettings> {
            Some(self.settings.clone())
        }
        fn record(&self, _entry: McpLogEntry) {}
    }
    with_tables("ai", |session, users, _teams| async move {
        let socket = std::env::temp_dir().join(format!("tableport-mcp-oracle-{}.sock", std::process::id()));
        let mcp = tableport_core::start_mcp_server(socket.to_string_lossy().into(), "test".into(), Arc::new(Host { settings: session.settings() })).unwrap();
        let (reader, mut writer) = tokio::net::UnixStream::connect(&socket).await.unwrap().into_split();
        use tokio::io::{AsyncBufReadExt, AsyncWriteExt};
        let mut lines = tokio::io::BufReader::new(reader).lines();
        macro_rules! call {
            ($tool:expr, $arguments:expr) => {{
                let message = json!({ "jsonrpc": "2.0", "id": 1, "method": "tools/call", "params": { "name": $tool, "arguments": $arguments } });
                writer.write_all(format!("{message}\n").as_bytes()).await.unwrap();
                let reply: Value = serde_json::from_str(&lines.next_line().await.unwrap().unwrap()).unwrap();
                (reply["result"]["content"][0]["text"].as_str().unwrap_or_default().to_string(), reply["result"]["isError"].as_bool().unwrap_or(true))
            }};
        }
        let table = tableport_core::qualified_name(users.clone(), Engine::Oracle);
        let (text, error) = call!("run_read_query", json!({ "sql": format!("WITH t AS (SELECT name, score FROM {table}) SELECT * FROM t ORDER BY name;") }));
        assert!(!error && text.contains("\"Ada\"") && text.contains("9.5"), "{text}");
        for sql in [
            format!("DELETE FROM {table}"),
            format!("SELECT 1 FROM dual; DELETE FROM {table}"),
            format!("SELECT * FROM {table} FOR UPDATE"),
            format!("BEGIN DELETE FROM {table}; END;"),
        ] {
            let (text, error) = call!("run_read_query", json!({ "sql": sql }));
            assert!(error, "not refused: {sql} → {text}");
        }
        mcp.stop();
        assert_eq!(session.row_count(users.clone(), session.columns(users).await.unwrap(), Vec::new()).await.unwrap(), 5);
    })
    .await;
}
